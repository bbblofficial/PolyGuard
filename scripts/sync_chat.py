#!/usr/bin/env python3
"""Bring the Guard chat panel into the public site (pages/chat/).

app/static/ is the single source of truth for the chat UI. This script
copies its CSS/JS into pages/assets/chat.{css,js} and generates
pages/chat/index.html from app/static/index.html, rewriting paths so the
page works on GitHub Pages (and on the service under /site/chat/). In that
"pages" mode the script finds the live service through api/links.json.

    python scripts/sync_chat.py          # write the files
    python scripts/sync_chat.py --check  # exit 1 if pages/ is out of date

publish_status.sh runs it before every publish; tests/test_pages.py checks
that the committed copy is current.
"""
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATIC = ROOT / "app" / "static"
PAGES = ROOT / "pages"


def version() -> str:
    h = hashlib.sha1()
    for f in ("style.css", "script.js"):
        h.update((STATIC / f).read_bytes())
    return h.hexdigest()[:10]


def chat_html() -> str:
    s = (STATIC / "index.html").read_text(encoding="utf-8")
    v = version()
    subs = [
        ('<html lang="fa" dir="rtl">', '<html lang="fa" dir="rtl" data-api="pages" data-root="../">'),
        ("<title>Unicollect | نگهبان متن</title>",
         "<title>چت · Unicollect Guard</title>\n  <meta name=\"description\" content=\"چت Unicollect Guard: متن فارسی، فینگیلیش یا انگلیسی را بفرست و حکم پنج مدل را ببین.\">"),
        ('href="/static/fonts/', 'href="../assets/fonts/'),
        ('href="/static/favicon.svg"', 'href="../assets/favicon.svg"'),
        ('href="/static/style.css?v=__V__"', f'href="../assets/chat.css?v={v}"'),
        ('src="/static/script.js?v=__V__"', f'src="../assets/chat.js?v={v}"'),
        ('href="/site/" data-site-home', 'href="../" data-site-home'),
        # API docs live on this same site
        ('<a class="sb-item" href="/api-docs" target="_blank" rel="noopener">', '<a class="sb-item" href="../api/">'),
        ('<a class="icon-btn" href="/api-docs" target="_blank" rel="noopener"', '<a class="icon-btn" href="../api/"'),
        ('href="/api-docs" data-docs-href target="_blank" rel="noopener"', 'href="../api/" data-docs-href'),
        # Swagger is on the live service: filled in by data-live-href
        ('href="/docs" data-live-href="/docs"', 'aria-disabled="true" data-live-href="/docs"'),
    ]
    for a, b in subs:
        if a not in s:
            raise SystemExit(f"sync_chat: pattern not found in app/static/index.html: {a!r}")
        s = s.replace(a, b)
    s = re.sub(r'\s*<link rel="icon" type="image/svg\+xml" href="data:[^"]*">', "", s)
    banner = "<!-- generated by scripts/sync_chat.py from app/static/index.html; edit the source, not this file -->\n"
    return s.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + banner, 1)


def outputs():
    return {
        PAGES / "assets" / "chat.css": (STATIC / "style.css").read_text(encoding="utf-8"),
        PAGES / "assets" / "chat.js": (STATIC / "script.js").read_text(encoding="utf-8"),
        PAGES / "chat" / "index.html": chat_html(),
    }


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, text in outputs().items():
        cur = path.read_text(encoding="utf-8") if path.exists() else None
        if cur == text:
            continue
        stale.append(path.relative_to(ROOT))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if check and stale:
        print("pages chat is out of date, run: python scripts/sync_chat.py\n  " + "\n  ".join(map(str, stale)))
        return 1
    print("chat synced" if stale else "chat already in sync", *(f"\n  {p}" for p in stale))
    return 0


if __name__ == "__main__":
    sys.exit(main())
